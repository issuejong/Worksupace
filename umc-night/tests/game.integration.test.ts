import { randomUUID } from "node:crypto";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { NextRequest } from "next/server";
import { POST as joinTeam } from "../app/api/join/route";
import { POST as transferTeam } from "../app/api/transfer/route";
import { hash } from "../lib/server/auth";
import { db } from "../lib/server/db";
import { correctGrade, gradeCurrent, startRun, stateFor, submitAnswer, transitionRun } from "../lib/server/game";
import { changeSetup, setupState } from "../lib/server/setup";
import { inspectTeamTransfer, issueTeamTransfer } from "../lib/server/transfer";

const testUrl = process.env.TEST_DATABASE_URL;
if (testUrl) process.env.DATABASE_URL = testUrl;
const suite = testUrl ? describe : describe.skip;

suite("live game against isolated PostgreSQL", () => {
  const actor = randomUUID();
  const testIp = "192.0.2.31";
  let teamA = ""; let teamB = ""; let teamC = ""; let teamD = ""; let roundId = ""; let secondRoundId = ""; let ruleRoundId = ""; let liveRoundId = ""; let runId = ""; let ruleRunId = ""; let liveRunId = "";
  beforeAll(async () => {
    const sql = db();
    const existing = await sql`select count(*)::integer as count from public.teams`;
    if (existing[0].count !== 0) throw new Error("Integration test requires an empty dedicated database");
    roundId = (await sql`insert into public.rounds(title,position) values ('Test round',0) returning id`)[0].id;
    await sql`insert into public.questions(round_id,kind,prompt,options,correct_answer,duration_seconds,position) values (${roundId},'choice','Q1',${sql.json(["A","B"])},'A',60,0)`;
    await sql`insert into public.questions(round_id,kind,prompt,options,correct_answer,duration_seconds,position,practice) values (${roundId},'short','Practice',${sql.json([])},'yes',60,1,true)`;
    secondRoundId = (await sql`insert into public.rounds(title,position) values ('Second round',1) returning id`)[0].id;
    await sql`insert into public.questions(round_id,kind,prompt,options,correct_answer,duration_seconds,position) values (${secondRoundId},'choice','Q3',${sql.json(["C","D"])},'C',60,0)`;
  });
  afterAll(async () => {
    if (!testUrl) return;
    const sql = db();
    if (runId) await sql`delete from public.runs where id=${runId}`;
    if (ruleRunId) await sql`delete from public.runs where id=${ruleRunId}`;
    if (liveRunId) await sql`delete from public.runs where id=${liveRunId}`;
    if (roundId) await sql`delete from public.rounds where id=${roundId}`;
    if (secondRoundId) await sql`delete from public.rounds where id=${secondRoundId}`;
    if (ruleRoundId) await sql`delete from public.rounds where id=${ruleRoundId}`;
    if (liveRoundId) await sql`delete from public.rounds where id=${liveRoundId}`;
    await sql`delete from public.join_attempts where key_hash=${hash(testIp)}`;
    if (teamA) await sql`delete from public.teams where id in (${teamA},${teamB},${teamC},${teamD})`;
    await sql.end();
  });
  it("registers any number of teams by name and preserves each representative session", async () => {
    const join = (name: string, cookie?: string) => joinTeam(new NextRequest("http://localhost/api/join", {
      method: "POST",
      headers: { origin: "http://localhost", "content-type": "application/json", "x-forwarded-for": testIp, ...(cookie ? { cookie } : {}) },
      body: JSON.stringify({ action: "join", name }),
    }));
    const joinedA = await join("아코팀");
    expect(joinedA.status).toBe(200);
    teamA = (await joinedA.json()).team.id;
    const cookie = joinedA.headers.get("set-cookie")?.split(";")[0];
    expect(cookie).toContain("umc_team_session=");
    expect((await join("다른 이름", cookie)).status).toBe(200);
    expect((await join("아코팀")).status).toBe(409);
    const joinedB = await join("B");
    teamB = (await joinedB.json()).team.id;
    const joinedC = await join("C");
    teamC = (await joinedC.json()).team.id;
    const joinedD = await join("D");
    teamD = (await joinedD.json()).team.id;
    expect((await stateFor("screen")).teams).toHaveLength(4);
    expect((await db()`select number from public.teams where id=${teamD}`)[0].number).toBe(4);
    expect((await db()`select count(*)::integer as count from public.team_sessions where team_id=${teamA} and revoked_at is null`)[0].count).toBe(1);
  });
  it("hides answers until reveal, closes by database time, scores once, and reverses corrections", async () => {
    const started = await startRun("rehearsal"); runId = started.runId;
    const live = await transitionRun({ action: "start", version: started.version }, actor);
    const before = await stateFor("screen");
    expect(before.question).not.toHaveProperty("correctAnswer");
    const requestId = randomUUID();
    const answer = await submitAnswer(teamA, { value: "A", requestId, expectedVersion: 0 });
    expect(answer.version).toBe(1);
    expect(await submitAnswer(teamA, { value: "A", requestId, expectedVersion: 0 })).toMatchObject({ duplicate: true, version: 1 });
    await submitAnswer(teamB, { value: "B", requestId: randomUUID(), expectedVersion: 0 });
    const hidden = await stateFor("screen");
    expect(hidden.teams.find(team => team.id === teamA)).not.toHaveProperty("answer");
    await db()`update public.runs set deadline_at=clock_timestamp()-interval '1 second' where id=${runId}`;
    await expect(submitAnswer(teamC, { value: "A", requestId: randomUUID(), expectedVersion: 0 })).rejects.toMatchObject({ code: "ANSWER_CLOSED" });
    const closed = await transitionRun({ action: "close", version: live.version }, actor);
    expect((await stateFor("screen")).teams.find(team => team.id === teamA)).not.toHaveProperty("answer");
    const revealed = await transitionRun({ action: "reveal", version: closed.version }, actor);
    const publicState = await stateFor("screen");
    expect(publicState.question).toHaveProperty("correctAnswer", "A");
    expect(publicState.teams.find(team => team.id === teamA)).toHaveProperty("answer", "A");
    expect(publicState.teams.find(team => team.id === teamB)).toHaveProperty("answer", "B");
    expect(publicState.teams.find(team => team.id === teamC)).toHaveProperty("answer", null);
    expect((await stateFor("team", teamA)).teams.find(team => team.id === teamB)).not.toHaveProperty("answer");
    expect(publicState.scoresVisible).toBe(false);
    expect(publicState.teams.find(team => team.id === teamA)).not.toHaveProperty("earned");
    const graded = await gradeCurrent(actor, revealed.version, {});
    expect(graded.version).toBe(revealed.version + 1);
    const gradedAgain = await gradeCurrent(actor, revealed.version, {});
    expect(gradedAgain.duplicate).toBe(true);
    const state = await stateFor("host");
    expect(state.teams.find(team => team.id === teamA)?.score).toBe(1);
    expect(state.teams.find(team => team.id === teamB)?.score).toBe(0);
    const betweenQuestions = await stateFor("screen");
    expect(betweenQuestions.roundBreak).toBe(false);
    expect(betweenQuestions.teams.find(team => team.id === teamA)?.score).toBeNull();
    expect(betweenQuestions.teams.find(team => team.id === teamA)).toHaveProperty("answer", "A");
    const rqId = state.question?.id as string;
    await correctGrade(actor, { runQuestionId: rqId, teamId: teamB, correct: true, reason: "판정 정정" });
    expect((await stateFor("host")).teams.find(team => team.id === teamB)?.score).toBe(1);
    await correctGrade(actor, { runQuestionId: rqId, teamId: teamB, correct: false, reason: "판정 되돌림" });
    expect((await stateFor("host")).teams.find(team => team.id === teamB)?.score).toBe(0);
    const practice = await transitionRun({ action: "start", version: graded.version }, actor);
    const paused = await transitionRun({ action: "pause", version: practice.version }, actor);
    await expect(submitAnswer(teamA, { value: "yes", requestId: randomUUID(), expectedVersion: 0 })).rejects.toMatchObject({ code: "ANSWER_CLOSED" });
    const resumed = await transitionRun({ action: "resume", version: paused.version }, actor);
    await submitAnswer(teamA, { value: "yes", requestId: randomUUID(), expectedVersion: 0 });
    const practiceClosed = await transitionRun({ action: "close", version: resumed.version }, actor);
    const practiceRevealed = await transitionRun({ action: "reveal", version: practiceClosed.version }, actor);
    const practiceGraded = await gradeCurrent(actor, practiceRevealed.version, { [teamA]: true });
    expect((await stateFor("host")).teams.find(team => team.id === teamA)?.score).toBe(1);
    const roundResult = await stateFor("screen");
    expect(roundResult.roundBreak).toBe(true);
    expect(roundResult.scoresVisible).toBe(true);
    expect(roundResult.hasNextQuestion).toBe(true);
    expect(roundResult.teams.find(team => team.id === teamA)?.score).toBe(1);
    const voided = await transitionRun({ action: "void", version: practiceGraded.version }, actor);
    expect((await stateFor("host")).teams.find(team => team.id === teamA)?.score).toBe(1);
    expect((await stateFor("screen")).teams.find(team => team.id === teamA)).not.toHaveProperty("answer");
    const finalQuestion = await transitionRun({ action: "start", version: voided.version }, actor);
    const nextRound = await stateFor("screen");
    expect(nextRound.question?.roundTitle).toBe("Second round");
    expect(nextRound.scoresVisible).toBe(false);
    expect(nextRound.teams.find(team => team.id === teamA)?.score).toBeNull();
    await submitAnswer(teamA, { value: "C", requestId: randomUUID(), expectedVersion: 0 });
    const finalClosed = await transitionRun({ action: "close", version: finalQuestion.version }, actor);
    const finalRevealed = await transitionRun({ action: "reveal", version: finalClosed.version }, actor);
    const finalGraded = await gradeCurrent(actor, finalRevealed.version, {});
    expect((await stateFor("host")).teams.find(team => team.id === teamA)?.score).toBe(2);
    expect((await stateFor("screen")).roundBreak).toBe(true);
    expect((await stateFor("screen")).hasNextQuestion).toBe(false);
    const finished = await transitionRun({ action: "finish", version: finalGraded.version }, actor);
    expect(finished.phase).toBe("finished");
  });
  it("updates setup data and protects played teams and questions from deletion", async () => {
    const renamed = "아코팀 수정";
    await changeSetup({ action: "updateTeam", id: teamA, name: renamed });
    expect((await stateFor("screen")).teams.find(team => team.id === teamA)?.name).toBe(renamed);
    await expect(changeSetup({ action: "updateTeam", id: teamB, name: renamed })).rejects.toMatchObject({ code: "TEAM_NAME_TAKEN" });
    await expect(changeSetup({ action: "deleteTeam", id: teamA })).rejects.toMatchObject({ code: "TEAM_HAS_HISTORY" });

    const join = await joinTeam(new NextRequest("http://localhost/api/join", {
      method: "POST", headers: { origin: "http://localhost", "content-type": "application/json", "x-forwarded-for": testIp },
      body: JSON.stringify({ action: "join", name: "삭제할 팀" }),
    }));
    expect(join.status).toBe(200);
    const spareTeamId = (await join.json()).team.id;
    await changeSetup({ action: "deleteTeam", id: spareTeamId });
    expect((await setupState()).teams.some(team => team.id === spareTeamId)).toBe(false);

    const usedQuestion = (await db()`select id from public.questions where round_id=${roundId} and prompt='Q1'`)[0].id;
    await expect(changeSetup({ action: "deleteQuestion", id: usedQuestion })).rejects.toMatchObject({ code: "QUESTION_HAS_HISTORY" });
    await expect(changeSetup({ action: "deleteRound", id: roundId })).rejects.toMatchObject({ code: "ROUND_HAS_QUESTIONS" });

    const spareRound = await changeSetup({ action: "round", title: "임시 라운드", position: 2 });
    if (!("id" in spareRound)) throw new Error("Round creation failed");
    const spareRoundId = spareRound.id;
    await changeSetup({ action: "round", id: spareRoundId, title: "수정된 라운드", position: 3 });
    const spareQuestion = await changeSetup({ action: "question", roundId: spareRoundId, kind: "short", prompt: "임시 문제", correctAnswer: "정답", durationSeconds: 30, position: 0 });
    if (!("id" in spareQuestion)) throw new Error("Question creation failed");
    const spareQuestionId = spareQuestion.id;
    expect((await setupState()).questions.find(question => question.id === spareQuestionId)).not.toHaveProperty("points");
    expect((await db()`select points from public.questions where id=${spareQuestionId}`)[0].points).toBe(1);
    await changeSetup({ action: "question", id: spareQuestionId, roundId: spareRoundId, kind: "short", prompt: "수정된 문제", correctAnswer: "정답", durationSeconds: 40, position: 0 });
    expect((await setupState()).questions.find(question => question.id === spareQuestionId)?.prompt).toBe("수정된 문제");
    await changeSetup({ action: "deleteQuestion", id: spareQuestionId });
    await changeSetup({ action: "deleteRound", id: spareRoundId });
    expect((await setupState()).rounds.some(round => round.id === spareRoundId)).toBe(false);
  });
  it("moves a team to a replacement device once without losing its score", async () => {
    const oldSession = (await db()`select token_hash from public.team_sessions where team_id=${teamA} and revoked_at is null`)[0].token_hash;
    const first = await issueTeamTransfer(teamA);
    expect((await inspectTeamTransfer(first.token)).team.id).toBe(teamA);
    const second = await issueTeamTransfer(teamA);
    await expect(inspectTeamTransfer(first.token)).rejects.toMatchObject({ code: "TRANSFER_EXPIRED" });
    const response = await transferTeam(new NextRequest("http://localhost/api/transfer", {
      method: "POST", headers: { origin: "http://localhost", "content-type": "application/json" },
      body: JSON.stringify({ action: "redeem", token: second.token }),
    }));
    expect(response.status).toBe(200);
    expect((await response.json()).team.id).toBe(teamA);
    const newToken = response.headers.get("set-cookie")?.match(/umc_team_session=([^;]+)/)?.[1];
    expect(newToken).toBeTruthy();
    const sessions = await db()`select token_hash,revoked_at from public.team_sessions where team_id=${teamA}`;
    expect(sessions.find(row => row.token_hash === oldSession)?.revoked_at).not.toBeNull();
    expect(sessions.find(row => row.token_hash === hash(newToken!))?.revoked_at).toBeNull();
    expect((await stateFor("host")).teams.find(team => team.id === teamA)?.score).toBe(2);
    await expect(inspectTeamTransfer(second.token)).rejects.toMatchObject({ code: "TRANSFER_EXPIRED" });
    const expired = await issueTeamTransfer(teamA);
    await db()`update public.team_transfers set expires_at=now()-interval '1 second' where token_hash=${hash(expired.token)}`;
    await expect(inspectTeamTransfer(expired.token)).rejects.toMatchObject({ code: "TRANSFER_EXPIRED" });
    expect((await db()`select count(*)::integer as count from public.team_sessions where team_id=${teamA} and revoked_at is null`)[0].count).toBe(1);
  });
  it("waits for every starting team and awards only the earliest correct submission", async () => {
    const sql = db();
    ruleRoundId = (await sql`insert into public.rounds(title,position) values ('Rule round',-1) returning id`)[0].id;
    const ruleQuestion = await changeSetup({ action: "question", roundId: ruleRoundId, kind: "choice", prompt: "First correct wins", options: ["A", "B"], correctAnswer: "A", durationSeconds: 5, scoringMode: "first_correct", waitForAll: true, position: 0 });
    if (!("id" in ruleQuestion)) throw new Error("Rule question creation failed");
    expect((await setupState()).questions.find(question => question.id === ruleQuestion.id)?.scoring_mode).toBe("first_correct");
    const created = await startRun("rehearsal"); ruleRunId = created.runId;
    const live = await transitionRun({ action: "start", version: created.version }, actor);
    const publicState = await stateFor("screen");
    expect(publicState.question?.waitForAll).toBe(true);
    expect(publicState.question?.scoringMode).toBe("first_correct");
    expect(publicState.deadlineAt).toBeNull();
    expect(publicState.requiredTeamIds).toHaveLength(4);
    await submitAnswer(teamB, { value: "B", requestId: randomUUID(), expectedVersion: 0 });
    await submitAnswer(teamA, { value: "A", requestId: randomUUID(), expectedVersion: 0 });
    const firstTimestamp = (await sql`select updated_at from public.answers where team_id=${teamA} and run_question_id=${publicState.question!.id}`)[0].updated_at;
    expect((await submitAnswer(teamA, { value: "A", requestId: randomUUID(), expectedVersion: 1 })).version).toBe(1);
    expect((await sql`select updated_at from public.answers where team_id=${teamA} and run_question_id=${publicState.question!.id}`)[0].updated_at).toEqual(firstTimestamp);
    await expect(transitionRun({ action: "close", version: live.version }, actor)).rejects.toMatchObject({ code: "WAITING_FOR_TEAMS" });
    const paused = await transitionRun({ action: "pause", version: live.version }, actor);
    const resumed = await transitionRun({ action: "resume", version: paused.version }, actor);
    expect((await stateFor("host")).deadlineAt).toBeNull();
    await submitAnswer(teamC, { value: "A", requestId: randomUUID(), expectedVersion: 0 });
    await submitAnswer(teamD, { value: "B", requestId: randomUUID(), expectedVersion: 0 });
    const closed = await transitionRun({ action: "close", version: resumed.version }, actor);
    const revealed = await transitionRun({ action: "reveal", version: closed.version }, actor);
    const graded = await gradeCurrent(actor, revealed.version, {});
    const scores = () => stateFor("host").then(state => new Map(state.teams.map(team => [team.id, team.score])));
    expect((await scores()).get(teamA)).toBe(1);
    expect((await scores()).get(teamC)).toBe(0);
    await correctGrade(actor, { runQuestionId: publicState.question!.id, teamId: teamA, correct: false, reason: "판정 정정" });
    expect((await scores()).get(teamA)).toBe(0);
    expect((await scores()).get(teamC)).toBe(1);
    await correctGrade(actor, { runQuestionId: publicState.question!.id, teamId: teamB, correct: true, reason: "판정 정정" });
    expect((await scores()).get(teamB)).toBe(1);
    expect((await scores()).get(teamC)).toBe(0);
    await transitionRun({ action: "finish", version: graded.version }, actor);
  });
  it("lets the host choose a live answer only when revealing a closed question", async () => {
    const sql = db();
    liveRoundId = (await sql`insert into public.rounds(title,position) values ('Balance round',-2) returning id`)[0].id;
    const createdQuestion = await changeSetup({ action: "question", roundId: liveRoundId, kind: "choice", prompt: "산 또는 바다?", options: ["산", "바다"], correctAnswer: "", answerMode: "live", durationSeconds: 60, position: 0 });
    if (!("id" in createdQuestion)) throw new Error("Live-answer question creation failed");
    const storedQuestion = (await setupState()).questions.find(question => question.id === createdQuestion.id);
    expect(storedQuestion?.answer_mode).toBe("live");
    expect(storedQuestion?.correct_answer).toBeNull();
    const createdRun = await startRun("rehearsal"); liveRunId = createdRun.runId;
    const live = await transitionRun({ action: "start", version: createdRun.version }, actor);
    expect((await stateFor("screen")).question).not.toHaveProperty("correctAnswer");
    expect((await stateFor("host")).question).not.toHaveProperty("correctAnswer");
    await submitAnswer(teamA, { value: "산", requestId: randomUUID(), expectedVersion: 0 });
    await submitAnswer(teamB, { value: "바다", requestId: randomUUID(), expectedVersion: 0 });
    const closed = await transitionRun({ action: "close", version: live.version }, actor);
    await expect(transitionRun({ action: "reveal", version: closed.version }, actor)).rejects.toMatchObject({ code: "ANSWER_REQUIRED" });
    await expect(transitionRun({ action: "reveal", version: closed.version, answer: "없음" }, actor)).rejects.toMatchObject({ code: "ANSWER_INVALID" });
    expect((await stateFor("screen")).question).not.toHaveProperty("correctAnswer");
    const revealed = await transitionRun({ action: "reveal", version: closed.version, answer: "바다" }, actor);
    expect((await stateFor("screen")).question).toHaveProperty("correctAnswer", "바다");
    const graded = await gradeCurrent(actor, revealed.version, {});
    const host = await stateFor("host");
    expect(host.teams.find(team => team.id === teamA)?.score).toBe(0);
    expect(host.teams.find(team => team.id === teamB)?.score).toBe(1);
    await transitionRun({ action: "finish", version: graded.version }, actor);
  });
});
